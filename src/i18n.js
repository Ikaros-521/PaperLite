Object.assign(DICT.zh, MOBILE_DICT.zh);
Object.assign(DICT.en, MOBILE_DICT.en);

// 取文案：en 缺失回退 zh，zh 也缺失回退 key；{x} 占位插值
export function tr(lang, key, params) {
  const d = DICT[lang] || DICT.zh;
  let s = d[key];
  if (s == null) s = DICT.zh[key];
  if (s == null) return key;
  if (params) {
    for (const k in params) s = s.split('{' + k + '}').join(String(params[k]));
  }
  return s;
}

// 供非 React 模块（linter/llm）使用：读模块级当前语言
export function t(key, params) {
  return tr(currentLang, key, params);
}
