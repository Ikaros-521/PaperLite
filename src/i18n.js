import { MOBILE_DICT } from './flows/mobile/i18n/index.js';

export const LS_LANG = 'paperlite.lang';
export const LANGS = ['zh', 'en'];
export function detectLang() {
  try {
    const s = localStorage.getItem(LS_LANG);
    if (s === 'zh' || s === 'en') return s;
  } catch (e) { /* ignore */ }
  try {
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return /^en\b/i.test(nav) ? 'en' : 'zh';
  } catch (e) { return 'zh'; }
}

// 非 React 模块（linter/llm 等）读取的模块级当前语言；App 渲染时同步
let currentLang = 'zh';
export function setLang(l) { if (l === 'zh' || l === 'en') currentLang = l; }
export function getLang() { return currentLang; }

